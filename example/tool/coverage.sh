#!/bin/bash
# Line coverage of the klinex library (repo root) and of this demo app.
# Every file under lib/ is imported by test/coverage_all_test.dart, so untested files count as 0%.
# Generated code (lib/l10n/generated/) is excluded. Usage: tool/coverage.sh [min-percent]
set -e
cd "$(dirname "$0")/../.."
min=${1:-80}
status=0

report() {
  local dir=$1 pkg=$2
  (
    cd "$dir"
    {
      echo '// Imports every file under lib/ so coverage counts untested files as 0%.'
      echo '// Regenerated by example/tool/coverage.sh.'
      echo '// ignore_for_file: unused_import'
      echo
      find lib -name '*.dart' -not -path 'lib/l10n/generated/*' | sort |
        sed -E "s#^lib/(.*)#import 'package:$pkg/\1';#"
      echo
      echo 'void main() {}'
    } > test/coverage_all_test.dart
    dart format -l 100 test/coverage_all_test.dart > /dev/null
    rm -rf coverage
    flutter test --coverage -j 1 > /tmp/klinex_coverage_$pkg.log 2>&1 || {
      tail -20 /tmp/klinex_coverage_$pkg.log
      exit 1
    }
    awk -F: -v pkg="$pkg" -v min="$min" '
      /^SF:/ { skip = ($2 ~ /lib\/l10n\/generated\//) }
      /^LF:/ && !skip { lf += $2 }
      /^LH:/ && !skip { lh += $2 }
      END {
        pct = lh * 100 / lf
        printf "%-16s %5.1f%% (%d/%d)\n", pkg, pct, lh, lf
        exit pct < min
      }' coverage/lcov.info
  ) || status=1
}

report . klinex
report example klinex_example
exit $status
